/**
 * Calculate total payable fee breakdown for any student
 */
export function calculateStudentFees(student: Student) {
  const tuition = student.monthlyTuitionFee || 0;
  // If boardingStatus is আবাসিক, apply boarding fee, otherwise 0
  const isResidential = student.boardingStatus === 'আবাসিক';
  const boarding = isResidential ? (student.boardingFee || 2500) : 0;
  const exam = student.examFee || 0;
  const total = tuition + boarding + exam;

  return {
    tuition,
    boarding,
    exam,
    total,
    isResidential,
  };
}
